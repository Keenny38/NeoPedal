"""Write docs/design-system.md: the design system of NeoPedal, numbers read from the code that defines them

Usage: py tools/gen_design_system.py       (run again after changing a token, a theme color or a component)
Prose is in this file, tables come from neopedal/theme_data.py, neopedal/ui/tokens.py, the Theme object of the QML
pages and the first comment of every component of neopedal/ui/qml/components.
"""

import os
import sys

os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)

from PySide6.QtGui import QColor
from PySide6.QtWidgets import QApplication

OUTPUT = os.path.join(ROOT, "docs", "design-system.md")
SURFACES = ("surfacePage", "surfaceCard", "surfaceFlyout", "surfaceSunken", "surfaceHover", "raised")
TEXT_COLORS = (("text", 7.0), ("dimText", 4.5), ("accent", 4.5), ("info", 4.5), ("gain", 4.5), ("loss", 4.5),
               ("warning", 4.5), ("purple", 4.5), ("gold", 4.5), ("controlBorder", 3.0))
PALETTE_ROLES = ("Window", "Base", "Button", "Midlight", "Mid", "Text", "PlaceholderText", "Highlight", "Link")


def table(header: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def component_rows() -> list[list[str]]:
    folder = os.path.join(ROOT, "neopedal", "ui", "qml", "components")
    rows = []
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".qml"):
            continue
        summary = ""
        with open(os.path.join(folder, name), encoding="utf-8") as file:
            for line in file:
                if line.startswith("//"):
                    summary = line[2:].strip()
                    break
        rows.append([f"`{name[:-4]}`", summary.replace("|", "/") or "-"])
    return rows


def main() -> int:
    app = QApplication.instance() or QApplication([])
    from neopedal import theme_data
    from neopedal.ui import set_style_palette
    from neopedal.ui.quick import FONT_SCALE, ICON_SCALE, SPACE_SCALE, Theme, contrast_ratio
    from neopedal.ui.tokens import (
        CONTROL_BORDER_CONTRAST,
        LEGACY_RADIUS,
        MOTION,
        RADIUS_SCALE,
        SIZE_SCALE,
        SURFACE_LIFT,
        TINT_LEVELS,
    )

    out = ["# NeoPedal design system", "",
           "Generated by `tools/gen_design_system.py` from the code: change a value there, then run the tool again.",
           "Related checks: `tests/test_theme_contrast.py` (contrast), `tests/test_qml_design_tokens.py` (token scales),",
           "`tests/test_hardcoded_colors.py` (no new hard coded color or size), `tools/theme_contrast.py`,",
           "`tools/theme_inventory.py`.", ""]
    out += ["## 1. Principles", "",
            "1. **Readable at a meter**: overlays are read at a glance, on a game screen; text is large, values are",
            "   monospace figures that never jump (tabular digits), labels are small and dim.",
            "2. **Calm**: surfaces are neutral, one accent color means selection and the main action; colors that carry a",
            "   meaning (gain, loss, warning, best, class) are the only others.",
            "3. **One identity** for the app window, the overlays, the web dashboard, the stream pages and the VR layer: the",
            "   same four themes, the same status colors (`neopedal/template/setting_status_colors.py`), the same grays",
            "   (`neopedal/theme_data.py`).",
            "4. **Tokens, not numbers**: a page asks the theme for a color, a size, a radius, a duration. A value drawn with",
            "   its own number is a defect to convert, and the ratchet tests stop it from growing.", ""]

    out += ["## 2. Color", "", "### Themes", "",
            "Four themes, chosen separately for the window (`window_color_theme`) and for the overlays (`overlay_theme`):", ""]
    out += [table(["Theme", "Window", "Look", "Used for"], [
        ["Modern Dark", "slate dark", "modern", "default; blue-tinted grays"],
        ["Modern Grey", "neutral gray", "modern", "same blue accent, no blue tint in surfaces"],
        ["Modern White", "light", "modern", "light panels, dark text"],
        ["Legacy Grey", "classic gray", "classic", "TinyPedal 2.50 look: classic layout & colors, smaller corners"]]), ""]
    out += ["Colorblind safe colors (`enable_colorblind_colors`) are an option on top of any theme (Okabe-Ito: red / green",
            "pairs become vermillion / blue).", "", "### Window palettes", ""]
    header = ["Role", *list(theme_data.THEME_NAMES)]
    rows = [[f"`{role}`"] + [f"`{theme_data.WINDOW_PALETTES[name][role][0]}`" for name in theme_data.THEME_NAMES]
            for role in PALETTE_ROLES]
    out += [table(header, rows), "", "Active color of each role; inactive and disabled variants are in",
            "`neopedal/theme_data.py` (`WINDOW_PALETTES`).", ""]
    out += ["### Status colors", "", "Colors that carry a meaning, per window theme (`STATUS_COLORS`):", ""]
    keys = list(theme_data.STATUS_COLORS["Dark"])
    out += [table(["Name", "Dark themes", "Light theme"],
                  [[f"`{key}`", f"`{theme_data.STATUS_COLORS['Dark'][key]}`", f"`{theme_data.STATUS_COLORS['Light'][key]}`"]
                   for key in keys]), ""]
    out += ["Class colors follow the game classes (Hypercar red, GT3 green, GTE yellow); the best of a class is purple,",
            "a personal best green, a slower sector yellow (`setting_status_colors`, shared by overlays, app pages and",
            "stream graphics).", "", "### Contrast", "",
            f"Minimums (WCAG 2.x): main text 7:1, other text 4.5:1, outline of a control {CONTROL_BORDER_CONTRAST:g}:1",
            "(`Theme.controlBorder`: the palette border color moved toward the text color until it holds on the page, the",
            "cards and the menus). Measured on every surface of every theme:", ""]
    for name in theme_data.THEME_NAMES:
        set_style_palette(name)
        theme = Theme()
        rows = []
        for surface_name in SURFACES:
            surface = getattr(theme, surface_name)
            cells = []
            for label, _ in TEXT_COLORS:
                if label == "controlBorder" and surface_name in ("surfaceHover", "raised"):
                    cells.append("-")
                else:
                    cells.append(f"{contrast_ratio(getattr(theme, label), surface):.1f}")
            rows.append([f"`{surface_name}` `{surface.name()}`", *cells])
        white = QColor("white")
        out += [f"**{name}**", "", table(["Surface"] + [label for label, _ in TEXT_COLORS], rows),
                f"White text on a filled accent button: {contrast_ratio(white, theme.accentFill):.1f}:1, on a filled "
                f"loss button: {contrast_ratio(white, theme.lossFill):.1f}:1.", ""]
    set_style_palette("Modern Dark")
    out += ["### Overlay colors", "",
            "Overlays are drawn in classic colors and recolored by the overlay theme (`widget/_style.py`): the classic gray",
            "scale maps to the slate scale of Modern Dark (`MODERN_PALETTE`), the neutral scale of Modern Grey",
            "(`MODERN_GREY_NEUTRALS`) or the reversed scale of Modern White (`MODERN_LIGHT_NEUTRALS`). Only options still at",
            "their default value are recolored: a color the user chose is kept. Web pages (dashboard, stream editor, Broadcast",
            "Director) use the same grays through `themed_page`.", ""]

    out += ["## 3. Typography", "",
            "- **Overlays**: values in JetBrains Mono (tabular figures), labels in Barlow; `enable_modern_font` off keeps",
            "  each overlay in its own font.",
            "- **App pages**: the system UI font at the base point size; Segoe Fluent Icons / MDL2 Assets for glyphs.",
            "- Sizes are factors of the base point size (`theme.fontSmall`...), never pixels:", ""]
    out += [table(["Token", "Factor"], [[f"`{key}`", f"{value:g}"] for key, value in FONT_SCALE.items()]), "",
            "Times, lap times and gaps use tabular digits so columns do not move while they change.", ""]

    out += ["## 4. Space, shape, elevation", "",
            "All sizes are factors of `em` (the base font size in pixels, scaled with the screen DPI).", ""]
    out += [table(["Token", "Factor of em"], [[f"`{key}`", f"{value:g}"] for key, value in SPACE_SCALE.items()]), ""]
    out += ["Control and row heights:", "",
            table(["Token", "Factor of em"], [[f"`{key}`", f"{value:g}"] for key, value in SIZE_SCALE.items()]), "",
            "Corner radius (Legacy themes: " + f"{LEGACY_RADIUS:g}" + " times as round):", "",
            table(["Token", "Factor of em"], [[f"`{key}`", f"{value:g}"] for key, value in RADIUS_SCALE.items()]), "",
            "Elevation is a lift of the card color toward white (dark themes) or toward the text color (light themes), by",
            "level, plus a shadow strength per theme:", "",
            table(["Level", "Share"], [[f"`{key}`", f"{value:g}"] for key, value in SURFACE_LIFT.items()]), "",
            "Tints (a color over a surface), `theme.tint(color, level)`:", "",
            table(["Level", "Alpha"], [[f"`{key}`", f"{value:g}"] for key, value in TINT_LEVELS.items()]), ""]
    out += ["Borders: a card has a subtle stroke (`theme.strokeSubtle`); a field, combo box or switch has the 3:1 outline",
            "(`theme.controlBorder`), lighter or darker when hovered (`theme.strokeStrong`); focus is a 2 px accent ring",
            "with a gap (`FocusRing`).", ""]

    out += ["## 5. Motion", "",
            table(["Token", "Milliseconds"], [[f"`{key}`", str(value)] for key, value in MOTION.items()]), "",
            "Durations are 0 when Windows animations are off. The Qt animation step follows the screen refresh rate",
            "(`animation_rate.py`). Things that move: a switch knob, a color change of a control, a page entering. Things",
            "that never animate: live values, tables and anything a driver reads while driving.", ""]

    out += ["## 6. Icons", "",
            "One set: Segoe Fluent Icons / MDL2 Assets (`theme.iconFont`, glyph codes checked on a rendered sheet), with a",
            "text fallback where the font is missing. Flags come from the flag-icons sheet (`TpFlag`). Sizes:", "",
            table(["Token", "Factor of em"], [[f"`{key}`", f"{value:g}"] for key, value in ICON_SCALE.items()]), ""]

    out += ["## 7. Components", "",
            "Shared QML components (`neopedal/ui/qml/components`), each with its first comment line:", "",
            table(["Component", "Role"], component_rows()), "",
            "States every interactive component handles: rest, hover, pressed, keyboard focus (ring), disabled",
            "(`theme.disabledOpacity`), and for fields an invalid state (loss color outline). Empty, loading and error",
            "states are `EmptyState`, `TpLoadingState` and `TpStateView`; messages use `TpNotice` and `TpToast` with the",
            "levels info, success, warning, error.", ""]

    out += ["## 8. Overlays in game", "",
            "- Panels keep an opacity (`background_opacity_percentage`, 92 by default) and a global overlay opacity",
            "  multiplies every overlay.",
            "- Modern design panels use rounded corners and a one pixel hairline; `enable_black_background` draws neutral",
            "  black on the dark themes.",
            "- Legibility on bright and dark circuits comes from panel opacity, not from outlines on text.", ""]

    out += ["## 9. Accessibility", "",
            "1. Text 4.5:1 minimum, main text 7:1, control outlines 3:1, on every surface of every theme (tested).",
            f"2. Click targets at least {SIZE_SCALE['minTarget']:g} em (24 px at 100 % scale).",
            "3. Every control is reachable by keyboard (Tab), shows a focus ring and answers Enter or Space; Esc closes a page.",
            "4. Meaning never rests on color alone: a switch that is on shows a check mark, status chips carry a word or a",
            "   glyph, and the colorblind safe option recolors overlays and pages.", "",
            "## 10. Changing the design system", "",
            "1. A color goes in `neopedal/theme_data.py` (themes), `neopedal/ui/tokens.py` (derived surfaces and strokes) or",
            "   `neopedal/template/setting_status_colors.py` (status), never in a page.",
            "2. Run `py tools/theme_contrast.py`: no value may fall under its minimum.",
            "3. Run `py tools/theme_inventory.py`: the counts may only go down (`tests/test_hardcoded_colors.py`).",
            "4. Run `py tools/gen_design_system.py` and commit the document with the change.", ""]
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(out))
    app.quit()
    print(f"saved {os.path.relpath(OUTPUT, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
